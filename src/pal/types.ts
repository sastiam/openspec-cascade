/**
 * Provider Abstraction Layer (PAL) Canonical Message Schema & Type Definitions.
 *
 * Implements the Provider-Agnostic Multi-Agent Looper specification defined in
 * `projects/agnostic_looper/SPECIFICATION.md` Section 4.
 *
 * Establishes the universal canonical message and content block data model,
 * standardized PAL error taxonomy, port interfaces, and provider payload contracts.
 */

import { randomUUID } from "node:crypto";

/**
 * Canonical PAL roles avoiding magic strings.
 */
export const PAL_ROLES = {
  SYSTEM: "system",
  USER: "user",
  ASSISTANT: "assistant",
  TOOL: "tool",
} as const;

export type PalRole = (typeof PAL_ROLES)[keyof typeof PAL_ROLES];
export type PalMessageRole = PalRole;

