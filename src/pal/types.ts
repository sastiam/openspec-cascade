/**
 * Canonical PAL Text Content Block.
 */
export interface PalTextContent {
  type: "text";
  text: string;
  cacheControl?: { type: "ephemeral" };
}

/**
 * Canonical PAL Thought / Extended Reasoning Content Block.
 * Preserves reasoning chains and cryptographic signatures (e.g. Claude 3.7).
 */
export interface PalThoughtContent {
  type: "thought";
  text: string;
  signature?: string;
  redacted?: boolean;
}

/**
 * Canonical PAL Tool Call Content Block.
 * Represents an invocation generated by the model.
 */
export interface PalToolCallContent {
  type: "tool_call";
  id: string;
  name: string;
  arguments: Record<string, unknown>;
  rawArguments?: string;
}

/**
 * Canonical PAL Tool Result Content Block.
 * Represents the execution outcome of a prior tool call.
 */
export interface PalToolResultContent {
  type: "tool_result";
  toolCallId: string;
  toolName: string;
  content: string | PalContentBlock[];
  isError: boolean;
  durationMs?: number;
}

/**
 * Canonical PAL Image Content Block.
 * Represents base64-encoded image payloads.
 */
export interface PalImageContent {
  type: "image";
  mimeType: PalImageMimeType;
  data: string; // Base64 encoded payload
}

/**
 * Union of all canonical PAL content blocks.
 */
export type PalContentBlock =
  | PalTextContent
  | PalThoughtContent
  | PalToolCallContent
  | PalToolResultContent
  | PalImageContent;

/**
 * Canonical PAL Message representation.
 */
export interface PalMessage {
  id: string; // UUID v4
  role: PalRole;
  content: PalContentBlock[];
  name?: string; // Semantic agent sender (e.g. "orchestrator", "worker", "reviewer")
  timestamp: string; // ISO 8601 UTC
  metadata?: Record<string, unknown>;
}

/**
 * Type guard for PalTextContent.
 */
export function isPalTextContent(block: PalContentBlock): block is PalTextContent {
  return block.type === PAL_CONTENT_BLOCK_TYPES.TEXT;
}

/**
 * Type guard for PalThoughtContent.
 */
export function isPalThoughtContent(block: PalContentBlock): block is PalThoughtContent {
  return block.type === PAL_CONTENT_BLOCK_TYPES.THOUGHT;
}

/**
 * Type guard for PalToolCallContent.
 */
export function isPalToolCallContent(block: PalContentBlock): block is PalToolCallContent {
  return block.type === PAL_CONTENT_BLOCK_TYPES.TOOL_CALL;
}

/**
 * Type guard for PalToolResultContent.
 */
export function isPalToolResultContent(block: PalContentBlock): block is PalToolResultContent {
  return block.type === PAL_CONTENT_BLOCK_TYPES.TOOL_RESULT;
}

/**
 * Type guard for PalImageContent.
 */
export function isPalImageContent(block: PalContentBlock): block is PalImageContent {
  return block.type === PAL_CONTENT_BLOCK_TYPES.IMAGE;
}

/**
 * Parameters for creating a canonical PAL message.
 */
export interface CreatePalMessageParams {
  role: PalRole;
  content: PalContentBlock[];
  name?: string;
  metadata?: Record<string, unknown>;
  id?: string;
  timestamp?: string;
}

/**
 * Factory creating a canonical PalMessage with defaults.
 */
export function createPalMessage(params: CreatePalMessageParams): PalMessage {
  return {
    id: params.id ?? randomUUID(),
    role: params.role,
    content: params.content,
    ...(params.name !== undefined ? { name: params.name } : {}),
    timestamp: params.timestamp ?? new Date().toISOString(),
    ...(params.metadata !== undefined ? { metadata: params.metadata } : {}),
  };
}

/**
 * Factory creating a canonical PalTextContent block.
 */
export function createTextBlock(
  text: string,
  cacheControl?: { type: "ephemeral" }
): PalTextContent {
  return {
    type: PAL_CONTENT_BLOCK_TYPES.TEXT,
    text,
    ...(cacheControl !== undefined ? { cacheControl } : {}),
  };
}

/**
 * Options for creating a canonical PalThoughtContent block.
 */
export interface CreateThoughtBlockOptions {
  signature?: string;
  redacted?: boolean;
}

/**
 * Factory creating a canonical PalThoughtContent block.
 */
export function createThoughtBlock(
  text: string,
  options?: CreateThoughtBlockOptions
): PalThoughtContent {
  return {
    type: PAL_CONTENT_BLOCK_TYPES.THOUGHT,
    text,
    ...(options?.signature !== undefined ? { signature: options.signature } : {}),
    ...(options?.redacted !== undefined ? { redacted: options.redacted } : {}),
  };
}

/**
 * Factory creating a canonical PalToolCallContent block.
 */
export function createToolCallBlock(
  id: string,
  name: string,
  args: Record<string, unknown>,
  rawArguments?: string
): PalToolCallContent {
  return {
    type: PAL_CONTENT_BLOCK_TYPES.TOOL_CALL,
    id,
    name,
    arguments: args,
    ...(rawArguments !== undefined ? { rawArguments } : {}),
  };
}

/**
 * Factory creating a canonical PalToolResultContent block.
 */
export function createToolResultBlock(
  toolCallId: string,
  toolName: string,
  content: string | PalContentBlock[],
  isError: boolean = false,
  durationMs?: number
): PalToolResultContent {
  return {
    type: PAL_CONTENT_BLOCK_TYPES.TOOL_RESULT,
    toolCallId,
    toolName,
    content,
    isError,
    ...(durationMs !== undefined ? { durationMs } : {}),
  };
}

/**
 * Factory creating a canonical PalImageContent block.
 */
export function createImageBlock(
  mimeType: PalImageMimeType,
  data: string
): PalImageContent {
  return {
    type: PAL_CONTENT_BLOCK_TYPES.IMAGE,
    mimeType,
    data,
  };
}

