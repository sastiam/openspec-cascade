import { describe, expect, test } from "bun:test";
import {
  BUDGET_CONSTANTS,
  CONSTANTS,
  DIAGRAM_CONSTANTS,
  ENGINE_CONSTANTS,
  EXIT_CODE_CONSTANTS,
  FORMAT_CONSTANTS,
  GIT_CONSTANTS,
  GREPTILE_CONSTANTS,
  GUARDRAIL_CONSTANTS,
  RUNTIME_CONSTANTS,
  SDD_CONSTANTS,
  TELEMETRY_CONSTANTS,
  TIMEOUT_CONSTANTS,
  VERIFY_CONSTANTS,
} from "../../config";
import { ROLLBACK_CONSTANTS } from "../../src/engine/rollback_buffer";
import { CLAUDE_ADAPTER_CONSTANTS } from "../../src/pal/adapters/claude";
import { GEMINI_ADAPTER_CONSTANTS } from "../../src/pal/adapters/gemini";
import { JULES_ADAPTER_CONSTANTS } from "../../src/pal/adapters/jules";
import { OPENCODE_ADAPTER_CONSTANTS } from "../../src/pal/adapters/opencode";

describe("Centralized Immutable Constants Registry (F01)", () => {
  test("exposes all typed namespaces and preserves legacy CONSTANTS facade", () => {
    expect(RUNTIME_CONSTANTS.DEFAULT_MODE).toBe("v1");
    expect(RUNTIME_CONSTANTS.SUPPORTED_MODES).toEqual(["v1", "v2"]);
    expect(ENGINE_CONSTANTS.SUPPORTED_ENGINES).toEqual(["claude", "opencode", "antigravity"]);
    expect(BUDGET_CONSTANTS.MAX_BUDGET_PER_SESSION_USD).toBe(CONSTANTS.MAX_BUDGET_PER_SESSION_USD);
    expect(TIMEOUT_CONSTANTS.RATE_LIMIT_SLEEP_MS).toBe(CONSTANTS.RATE_LIMIT_SLEEP_MS);
    expect(GIT_CONSTANTS.PROTECTED_BRANCHES).toEqual(CONSTANTS.PROTECTED_BRANCHES);
    expect(SDD_CONSTANTS.SDD_CONSTITUTION_PATH).toBe(CONSTANTS.SDD_CONSTITUTION_PATH);
    expect(DIAGRAM_CONSTANTS.ARCHIFY_ACTION).toBe(CONSTANTS.ARCHIFY_ACTION);
    expect(EXIT_CODE_CONSTANTS.EXIT_CODE_FATAL).toBe(2);
    expect(FORMAT_CONSTANTS.ONE_LINE_MAX_LENGTH).toBe(CONSTANTS.ONE_LINE_MAX_LENGTH);
    expect(GREPTILE_CONSTANTS.DEFAULT_ENABLED).toBe(false);
    expect(TELEMETRY_CONSTANTS.DEFAULT_REDACT_SECRETS).toBe(true);
    expect(GUARDRAIL_CONSTANTS.REDACTED_VALUE).toBe("[REDACTED]");
    expect(VERIFY_CONSTANTS.DEFAULT_VERIFY).toEqual(CONSTANTS.DEFAULT_VERIFY);
  });

  test("unifies drifting adapter and rollback constants with centralized constants", () => {
    expect(OPENCODE_ADAPTER_CONSTANTS.RATE_LIMIT_SLEEP_MS).toBe(TIMEOUT_CONSTANTS.RATE_LIMIT_SLEEP_MS);
    expect(GEMINI_ADAPTER_CONSTANTS.RATE_LIMIT_SLEEP_MS).toBe(TIMEOUT_CONSTANTS.RATE_LIMIT_SLEEP_MS);
    expect(OPENCODE_ADAPTER_CONSTANTS.STDERR_TAIL_MAX_LENGTH).toBe(FORMAT_CONSTANTS.STDERR_TAIL_MAX_LENGTH);
    expect(GEMINI_ADAPTER_CONSTANTS.CLI_STDERR_TAIL_MAX_LENGTH).toBe(FORMAT_CONSTANTS.STDERR_TAIL_MAX_LENGTH);
    expect(JULES_ADAPTER_CONSTANTS.STDERR_TAIL_MAX_LENGTH).toBe(FORMAT_CONSTANTS.STDERR_TAIL_MAX_LENGTH);
    expect(CLAUDE_ADAPTER_CONSTANTS.DEFAULT_MODEL).toBe(ENGINE_CONSTANTS.DEFAULT_CLAUDE_MODEL);
    expect(OPENCODE_ADAPTER_CONSTANTS.DEFAULT_MODEL).toBe(ENGINE_CONSTANTS.DEFAULT_OPENCODE_MODEL);
    expect(JULES_ADAPTER_CONSTANTS.DEFAULT_MODEL).toBe(ENGINE_CONSTANTS.DEFAULT_JULES_MODEL);
    expect(ROLLBACK_CONSTANTS.COMMAND_TIMEOUT_MS).toBe(TIMEOUT_CONSTANTS.COMMAND_TIMEOUT_MS);
    expect(ROLLBACK_CONSTANTS.EXIT_CODE_SUCCESS).toBe(EXIT_CODE_CONSTANTS.EXIT_CODE_SUCCESS);
    expect(ROLLBACK_CONSTANTS.EXIT_CODE_TIMEOUT).toBe(EXIT_CODE_CONSTANTS.EXIT_CODE_TIMEOUT);
  });

  test("exposes domain-scoped minimum bound constants without cross-domain coupling", () => {
    expect(TIMEOUT_CONSTANTS.MIN_DURATION_MS).toBe(0);
    expect(SDD_CONSTANTS.MIN_REVIEW_DURATION_SECONDS).toBe(0);
    expect(SDD_CONSTANTS.SDD_MIN_REVIEW_DURATION_SECONDS).toBe(10);
    expect(GUARDRAIL_CONSTANTS.MIN_POSITIVE_INT).toBe(1);
  });
});
